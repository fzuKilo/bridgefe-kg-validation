"""基准数据集构建图（论文图 3），与图 4、图 5 同一画法：
python -m kgfem.plot_benchmark [--out 目录]

左：题目生成（参数空间 → 分档参数化抽样，A/B/C 档与长联 S，配色对应各档主要考查的知识层）；
中：每道题的输入描述及其变体（第 3.2 节）；右：两级参考答案（第 3.3 节）；底部：评估准则（第 3.4 节）。
文字均取自正文第 3 节。
"""
import argparse
import os

import matplotlib
matplotlib.use('Agg')
matplotlib.rcParams['pdf.fonttype'] = 42   # 嵌入 TrueType 字体（期刊要求）
import matplotlib.pyplot as plt

from . import plot_kg
from .plot_ablation import INK2
from .plot_framework import region, textbox
from .plot_kg import LAYER_STYLE, Canvas

ROOT = plot_kg.ROOT


def fig_benchmark():
    fig, ax = plt.subplots(figsize=(7.2, 3.9))
    ax.set_xlim(0, 12)
    ax.set_ylim(-0.05, 6.45)
    ax.set_aspect('equal')
    ax.axis('off')
    c = Canvas(ax)

    def box(key, x, y, w, h, layer, title, body, fs=5.4):
        textbox(ax, x, y, w, h, layer, title, body, fs=fs, title_fs=6.3, align='center')
        c.box[key] = (x, y, w, h)

    lab = lambda x, y, t, col=INK2: ax.text(x, y, t, ha='center', va='center', fontsize=5.2, color=col,
                                            linespacing=1.1, bbox=dict(fc='white', ec='none', pad=0.4), zorder=5)
    TOP, BOT = 6.4, 1.45

    # ---- 题目生成
    region(ax, 0.1, BOT, 3.95, TOP, 'model', 'Problem generation (Sec. 3.1)')
    box('P', 2.0, 5.35, 3.6, 1.05, 'model', 'Parameter space',
        'spans, girders, bearings, piers, load class;\nprecast sections from the Zhejiang standard\n'
        'drawings (T 20–40 m, small box 25/30 m)')
    tiers = [('A', 1.05, 3.55, 'code', 'Tier A · 10', 'single-span simply\nsupported precast;\ncode provisions'),
             ('B', 2.95, 3.55, 'rule', 'Tier B · 10', '3–5-span precast,\ncontinuous after\nerection; modeling rules'),
             ('C', 1.05, 2.15, 'instance', 'Tier C · 10', 'cast-in-place box,\nunequal piers;\ntopological consistency'),
             ('S', 2.95, 2.15, 'constraint', 'Long units · 3', 'S01–S03,\n6/8/10 spans;\nscalability')]
    for key, x, y, layer, t, b in tiers:
        box(key, x, y, 1.75, 1.2, layer, t, b, fs=5.1)
    c.edge('P', 'A', None, pa=(2.0, 5.35 - 0.525), pb=(2.0, 4.15 + 0.02))
    lab(2.0, 4.47, 'parametric sampling')

    # ---- 输入描述
    region(ax, 4.4, BOT, 7.65, TOP, 'agent', 'Input description (Sec. 3.2)')
    box('I', 6.025, 5.0, 3.05, 1.6, 'agent', 'Four parts per problem',
        'span arrangement\nsection and material\nbearings and boundaries\n'
        'design standard (load class only,\nno load values)')
    box('V', 6.025, 2.75, 3.05, 2.15, 'agent', 'Input variants',
        'structured (main experiments)\n'
        'free text: A03, B04, C02 rewritten\nin Chinese and English as site notes,\n'
        'commission letter, and data sheet\n'
        '6 boundary cases + 6 unmodified\ncases for false alarms')
    c.edge('I', 'V', None, pa=(6.025, 5.0 - 0.8), pb=(6.025, 2.75 + 1.075))

    # ---- 参考答案
    region(ax, 8.1, BOT, 11.9, TOP, 'decision', 'Reference answers (Sec. 3.3)')
    box('D', 10.0, 5.0, 3.6, 1.6, 'decision', 'Decision level (primary)',
        'value and governing rule or provision\nof each decision; generated by a\n'
        'parametric reference program;\nreviewed by two bridge engineers')
    box('N', 10.0, 3.6, 3.6, 0.85, 'instance', 'Instance level',
        'spans, girders, sections, bearings, piers;\nseparates input-interpretation errors')
    box('R', 10.0, 2.2, 3.6, 1.4, 'constraint', 'Response level (auxiliary)',
        'reactions, midspan moments, $f_1$,\nlane-load moments; Tier A: analytical,\n'
        'checked with OpenSeesPy; B, C, S:\nindependent OpenSeesPy reference model')

    # 题目 → 输入描述 → 参考答案（同一道题）
    for x0, x1 in ((3.825, 4.5), (7.55, 8.2)):
        c.edge(None, None, None, pa=(x0, 3.9), pb=(x1, 3.9))
    # ---- 评估
    box('E', 6.0, 0.6, 11.8, 0.95, 'neutral', 'Evaluation criteria (Sec. 3.4)',
        'a run is correct only if the FE model executes and all decisions and responses are within 0.1% of the '
        'reference values;\nfailures are attributed to the earliest erroneous item: input interpretation, modeling '
        'rule, code parameter, topology, or execution')
    c.edge('V', 'E', None, pa=(6.025, 2.75 - 1.075), pb=(6.025, 0.6 + 0.475))
    lab(6.025, 1.32, 'tested approach → decisions, FE model')
    c.edge('R', 'E', None, pa=(10.0, 2.2 - 0.7), pb=(10.0, 0.6 + 0.475))
    lab(10.0, 1.32, 'reference values')
    return fig


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'paper_figures'))
    a = ap.parse_args()
    plt.rcParams['font.sans-serif'] = ['Arial', 'Helvetica', 'DejaVu Sans']
    plt.rcParams['axes.unicode_minus'] = False
    fig = fig_benchmark()
    p = os.path.join(a.out, 'fig3_benchmark_en')
    fig.savefig(p + '.png', dpi=300, facecolor='white', bbox_inches='tight', pad_inches=0.04)
    fig.savefig(p + '.pdf', facecolor='white', bbox_inches='tight', pad_inches=0.04)
    plt.close(fig)
    print(p)


if __name__ == '__main__':
    main()
